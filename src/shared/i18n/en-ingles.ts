/** El mensaje en inglés, o `undefined` si no se conoce. */
export function enIngles(texto: string): string | undefined {
  const exacto = EXACTOS[texto]
  if (exacto !== undefined) return exacto
  for (const [patron, decir] of PATRONES) {
    const m = patron.exec(texto)
    if (m === null) continue
    const dicho = decir(...m.slice(1).map((p) => p ?? undefined as unknown as string))
    if (dicho !== '') return dicho
  }
  return undefined
}

/** Un mensaje del dominio en el idioma de quien lo lee; sin traducción conocida, tal cual. */
export const traducir = (texto: string, t: T): string => t(texto, enIngles(texto) ?? texto)

/** Un objeto de etiquetas del dominio (vocabulario, ejemplos) con cada texto en el idioma de quien lo lee. */
export function traducirTodo<V>(valor: V, t: T): V {
  if (typeof valor === 'string') return traducir(valor, t) as V
  if (Array.isArray(valor)) return valor.map((v: unknown) => traducirTodo(v, t)) as V
  if (valor !== null && typeof valor === 'object') return Object.fromEntries(Object.entries(valor).map(([k, v]) => [k, traducirTodo(v, t)])) as V
  return valor
}
