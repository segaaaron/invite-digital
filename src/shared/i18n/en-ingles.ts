/** Lo que dice un aviso de la agenda tras «Hoy:», «Mañana:»…: el evento o sus cosas (con hora), cada una por su nombre. */
function queDeLaAgenda(que: string): string {
  if (que === 'es tu evento') return 'it’s your event'
  if (que === 'tu evento') return 'your event'
  const [lista, mas] = que.split(/ y (?=\d+ más$)/)
  const cosas = (lista ?? que).split(' · ').map((cosa) => {
    const m = /^(\d{1,2}:\d{2} )?(.*)$/.exec(cosa)
    return `${m?.[1] ?? ''}${EXACTOS[m?.[2] ?? ''] ?? m?.[2] ?? cosa}`
  })
  return cosas.join(' · ') + (mas === undefined ? '' : ` and ${mas.replace(' más', ' more')}`)
}

